export const USDT_HTML = `<span class="usdt">${usdtSvg()}<span>USDT</span></span>`;

/** Pone `text` en `el` con el logo de USDT delante de cada «USDT». */
export function textWithUsdt(el: HTMLElement, text: string): void {
  const parts = text.split('USDT');
  const nodes: Node[] = [];
  parts.forEach((part, i) => {
    if (part) nodes.push(document.createTextNode(part));
    if (i < parts.length - 1) {
      const span = document.createElement('span');
      span.className = 'usdt';
      span.innerHTML = `${usdtSvg()}<span>USDT</span>`;
      nodes.push(span);
    }
  });
  el.replaceChildren(...nodes);
}

