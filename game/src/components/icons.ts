// Íconos en pixel art (cuadrícula de 16×16, currentColor), dibujados con rectángulos y bordes nítidos.
// Cada ícono es un mapa de texto: '#' = pixel encendido, '.' = apagado. Sin fuentes de íconos ni internet.

/** Mapa de 16 filas de 16 caracteres → SVG de 24×24 con un <path> de cuadrados de 1×1. */
export function pixelIcon(rows: readonly string[], size = 24): string {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      // Une los pixeles seguidos de la fila en un solo rectángulo.
      let w = 1;
      while (row[x + w] === '#') w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return `<svg viewBox="0 0 16 16" width="${size}" height="${size}" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path d="${d}" fill="currentColor"/></svg>`;
}

